// Reference geometry (m).
export const AERO_S = 27.87, AERO_B = 9.144, AERO_CBAR = 3.45, XCG_REF = 0.35;

const clampIdx = (v, n) => Math.min(n - 1.0001, Math.max(0, v));
// Interpolate a 12-point alpha row.
function row(r, s) { const i = Math.floor(s), f = s - i; return r[i] + (r[i + 1] - r[i]) * f; }
// Interpolate a [k][alpha] table along both axes.
function tab2(t, sa, sk) { const k = Math.floor(sk), f = sk - k; const a = row(t[k], sa); return a + (row(t[k + 1], sa) - a) * f; }

// Total coefficients. alpha, beta in radians; el, ail, rdr in degrees; p, q, r in rad/s; V in m/s.
// xcg: centre of gravity as a fraction of the mean chord. Returns body-axis force coefficients
// (CX forward, CY right, CZ down) and moment coefficients (Cl roll right, Cm pitch up, Cn yaw right).
export function f16Coefficients(alpha, beta, el, ail, rdr, p, q, r, V, xcg = XCG_REF, out = {}) {
  const aDeg = alpha * 57.29578, bDeg = beta * 57.29578;
  // Beyond the data (stalled flight past 45°, or below -10°) hold the edge values, and let the
  // normal force approach that of a flat plate.
  const sa = clampIdx(aDeg / 5 + 2, 12);
  const se = clampIdx(el / 12 + 2, 5);
  const sbAbs = clampIdx(Math.abs(bDeg) / 5, 7), bSign = Math.sign(bDeg);
  const sb = clampIdx(bDeg / 10 + 3, 7);
  const dail = ail / 20, drdr = rdr / 30;
  let cz0 = row(CZ, sa);
  if (aDeg > 45) cz0 += (-1.9 * Math.sin(alpha) - cz0) * Math.min(1, (aDeg - 45) / 25);
  if (aDeg < -10) cz0 += (-1.9 * Math.sin(alpha) - cz0) * Math.min(1, (-10 - aDeg) / 20);
  const bRad = Math.min(Math.abs(beta), 0.6);
  const cx = tab2(CX, sa, se);
  const cy = -0.02 * Math.max(-30, Math.min(30, bDeg)) + 0.021 * dail + 0.086 * drdr;
  const cz = cz0 * (1 - bRad * bRad) - 0.19 * (el / 25);
  const cm = tab2(CM, sa, se);
  const cl = tab2(CL, sa, sbAbs) * bSign + tab2(DLDA, sa, sb) * dail + tab2(DLDR, sa, sb) * drdr;
  const cn = tab2(CN, sa, sbAbs) * bSign + tab2(DNDA, sa, sb) * dail + tab2(DNDR, sa, sb) * drdr;
  // Rate damping.
  const Vs = Math.max(V, 5);
  const cq = AERO_CBAR * q / (2 * Vs), b2v = AERO_B / (2 * Vs);
  out.cx = cx + cq * row(DAMP[0], sa);
  out.cy = cy + b2v * (row(DAMP[1], sa) * r + row(DAMP[2], sa) * p);
  out.cz = cz + cq * row(DAMP[3], sa);
  out.cl = cl + b2v * (row(DAMP[4], sa) * r + row(DAMP[5], sa) * p);
  out.cm = cm + cq * row(DAMP[6], sa) + out.cz * (XCG_REF - xcg);
  out.cn = cn + b2v * (row(DAMP[7], sa) * r + row(DAMP[8], sa) * p) - out.cy * (XCG_REF - xcg) * AERO_CBAR / AERO_B;
  // Local control effectiveness (per degree), for the flight control computer.
  out.cmEl = (tab2(CM, sa, clampIdx((el + 1) / 12 + 2, 5)) - tab2(CM, sa, clampIdx((el - 1) / 12 + 2, 5))) / 2 - 0.19 / 25 * (XCG_REF - xcg);
  out.clAil = tab2(DLDA, sa, sb) / 20; out.clRdr = tab2(DLDR, sa, sb) / 30;
  out.cnAil = tab2(DNDA, sa, sb) / 20; out.cnRdr = tab2(DNDR, sa, sb) / 30;
  return out;
}
